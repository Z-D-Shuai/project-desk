async (page) => {
  if(!page.url().startsWith('http://127.0.0.1:4318/'))throw new Error('仅可在独立验收服务运行');
  const bootstrap=await (await page.request.get('http://127.0.0.1:4318/api/bootstrap')).json();
  if(!bootstrap.storage.databasePath.includes('phase1-test-data'))throw new Error('拒绝操作正式数据库');
  await page.getByRole('link',{name:'项目档案',exact:true}).click();
  await page.getByRole('link',{name:'验收 · 暂停的创作',exact:true}).click();
  await page.getByRole('button',{name:'归档项目',exact:true}).click();
  await page.getByRole('button',{name:'确认归档',exact:true}).click();
  await page.getByRole('button',{name:'恢复项目',exact:true}).waitFor();
  await page.getByRole('link',{name:'项目档案',exact:true}).click();
  await page.getByText('4 个项目 · 未归档',{exact:true}).waitFor();
  await page.getByText('更多筛选',{exact:true}).click();
  await page.getByRole('combobox',{name:'归档范围',exact:true}).selectOption('archived');
  await page.getByText('1 个项目 · 已归档',{exact:true}).waitFor();
  await page.getByRole('link',{name:'验收 · 暂停的创作',exact:true}).click();
  await page.getByRole('img',{name:'完成度 68%',exact:true}).waitFor();
  await page.getByRole('button',{name:'恢复项目',exact:true}).click();
  await page.getByRole('button',{name:'确认恢复',exact:true}).click();
  await page.getByRole('button',{name:'归档项目',exact:true}).waitFor();
  await page.getByRole('link',{name:'项目档案',exact:true}).click();
  await page.getByRole('link',{name:'管理分类',exact:true}).click();
  await page.locator('.category-row').getByRole('button',{name:'删除',exact:true}).click();
  if(await page.getByRole('combobox',{name:/项目转移到/}).inputValue()!=='')throw new Error('默认转移目标应为未分类');
  await page.getByRole('button',{name:'确认转移并删除分类',exact:true}).click();
  await page.getByText('尚未创建分类',{exact:true}).waitFor();
  await page.getByRole('link',{name:'项目档案',exact:true}).click();
  await page.getByText('5 个项目 · 未归档',{exact:true}).waitFor();
  const categories=await page.locator('.category-cell').allTextContents();
  if(categories.length!==5 || categories.some(text=>text.trim()!=='未分类'))throw new Error('项目未完整转移到未分类');
  await page.setViewportSize({width:390,height:844});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('窄窗口横向溢出');
  await page.getByRole('button',{name:'新建项目',exact:true}).click();
  await page.getByRole('dialog',{name:'新建项目'}).waitFor();
  await page.screenshot({path:'PROJECT DESK/output/playwright/phase1/create-mobile.png'});
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:1440,height:900});
  await page.getByRole('link',{name:'总览',exact:true}).click();
  await page.getByRole('heading',{name:'总览',exact:true}).waitFor();
  console.log('PASS: archived list, restore without progress loss, delete category to uncategorized, mobile dialog');
}
